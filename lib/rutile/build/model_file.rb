module Rutile
  module Build
    # src/models/<model>.rs: the struct, its associations and enum
    # predicates, its methods, and its `Behavior`.
    class ModelFile
      ASSOCIATION_OPTIONS = %w[dependent class_name foreign_key optional inverse_of through source].freeze

      # has_many :through in the join-model shape: through a has_many on the
      # owner, sourced from a belongs_to on the join model, with no scope on
      # either and a join table that isn't the target's. [link, source], or
      # nil for any other shape.
      def self.through_parts(app, model, assoc)
        options = assoc["options"]
        link = app.association(model, options["through"])
        return nil unless link && link["macro"] == "has_many" && !link["options"]["through"]
        return nil unless (options.keys - %w[through source]).empty?

        source = app.association(link["class_name"], options["source"] || assoc["name"].delete_suffix("s"))
        return nil unless source && source["macro"] == "belongs_to"
        return nil if [link, source].any? { _1["options"]["scope"] }
        return nil if app.model(link["class_name"])["table_name"] == app.model(assoc["class_name"])["table_name"]

        [link, source]
      end

      def initialize(app, name)
        @app = app
        @name = name
        @model = app.model(name)
        @path = app.model_path(name)
        @uses = Uses.new
        @hooks = []
        @normalizers = []
        @exports = [name]
      end

      # The names src/models/mod.rs re-exports.
      attr_reader :exports

      def file_name = "#{Names.snake(@name)}.rs"

      # The Behavior chain is built first: it registers the hooks that the
      # inherent `impl` translates. The file reads struct, impl, Behavior.
      def to_rust
        raise Unsupported, "#{@path}: the namespaced model #{@name} isn't supported yet" if @name.include?("::")

        Declarations.check(@app, @path, Declarations::MODEL)
        @app.attempt { storable! }
        overrides!
        behavior = model_impl
        body = [struct, impl_block, behavior, *extras].compact
        header = "//! Generated by Rutile from #{@path}. Edit the Ruby, not this file."
        [header, @uses.lines("super"), *body].reject(&:empty?).join("\n\n") + "\n"
      end


      # A method the Behavior chain names, to be translated into `impl`.
      def hook(method) = (@hooks << method unless @hooks.include?(method))

      # The normalizer function the Behavior chain names.
      def normalizer(attribute, options) = @normalizers << ModelMacros.translate(@app, @name, attribute, options, @uses)

      # A callback block as a closure; it coerces to the `Hook` fn pointer.
      def closure(block)
        raise Unsupported.at(@path, block, "a callback block with parameters") if block.parameters

        lines = translate(block.body, block: true)
        ctx, record = parameter_names(lines)
        "|#{ctx}, #{record}| {\n#{lines.join("\n")}\nOk(())\n}"
      end

      # The model's scope trait, which mod.rs re-exports.
      def extras
        scopes = Scopes.for_model(@app, @uses, @name)
        @exports << "#{@name}Scopes" if scopes
        [scopes]
      end

      private

      # A method of Active Record's that the app replaces, wherever it is
      # (the model, ApplicationRecord, a concern), would be called by Rails
      # itself: `destroy`, `readonly?`. The runtime would call its own.
      def overrides!
        @app.overrides(@name).each do |override|
          source = override["source"]
          @app.attempt do
            raise Unsupported, "#{source["path"]}:#{source["line"]}: #{override["name"]}, which replaces Active Record's " \
                               "#{override["name"]}, isn't supported yet"
          end
        end
      end

      # What the runtime can't do for a table: key it on anything but id,
      # leave a column out of INSERT so the database computes it, share it
      # between classes by a type column, or check a lock_version on save.
      # Each would compile and quietly behave differently.
      def storable!
        table = @app.table(@name)
        raise Unsupported, "#{@path}: a primary key other than id isn't supported yet" unless table["primary_key"] == "id"

        base = @model.fetch("base_class")
        raise Unsupported, "#{@path}: single-table inheritance from #{base} isn't supported yet" unless base == @name

        @model["enums"].each do |attribute, values|
          raise Unsupported, "#{@path}: enum :#{attribute} with values other than integers isn't supported yet" unless values.values.all?(Integer)
        end

        locking = @model.fetch("locking_column")
        raise Unsupported, "#{@path}: optimistic locking on #{locking} isn't supported yet" if locking

        # The struct takes its defaults from the table; a model's own would
        # quietly give new records the database's instead.
        @model.fetch("model_defaults").each do |attribute|
          raise Unsupported, "#{@path}: a default for #{attribute} set in the model (enum default: or attribute) isn't supported yet"
        end

        table["columns"].each do |column|
          next unless column["default_function"] && column["name"] != "id"

          raise Unsupported, "#{@path}: the database default #{column["default_function"]} on #{column["name"]} isn't supported yet"
        end
      end

      def struct
        @uses.rt("model")
        fields = @app.columns(@name).filter_map { |column| @app.attempt { "#{column["name"]}: #{field_type(column)}#{field_default(column)}," } }
        "// #{@path}:#{@model.dig("source", "line")}\nmodel! {\npub struct #{@name} in #{Names.str(@model["table_name"])} {\n" \
          "#{fields.join("\n")}\n}\n}"
      end

      def field_type(column)
        type = @app.column_type(@name, column["name"])
        @uses.type(type)
        type.rust
      end

      # The database default as `model!`'s `= default`; an enum column's
      # integer default becomes its label.
      def field_default(column)
        default = column["default"]
        return "" if default.nil? || column["default_function"]

        if (values = @app.enum(@name, column["name"]))
          label = values.key(Integer(default, exception: false))
          return label ? " = #{Names.str(label)}" : ""
        end
        case column["type"]
        when "integer", "bigint" then " = #{Integer(default)}"
        when "float" then " = #{Float(default)}"
        when "boolean" then " = #{default == "true"}"
        when "string", "text" then " = #{Names.str(default)}"
        # INSERT writes every column, so a dropped default would be NULL.
        else
          raise Unsupported, "#{@path}: the default #{default} on the #{column["type"]} column #{column["name"]} isn't supported yet"
        end
      end

      def model_impl
        @uses.std("std::sync::LazyLock")
        @uses.rt("Behavior", "Model")
        chain = Behavior.new(@app, @name, @uses, self).lines
        "impl Model for #{@name} {\nfn behavior() -> &'static Behavior<Self> {\n" \
          "static BEHAVIOR: LazyLock<Behavior<#{@name}>> = LazyLock::new(|| {\nBehavior::<#{@name}>::new()\n" \
          "#{chain.join("\n")}\n});\n&BEHAVIOR\n}\n}"
      end

      def impl_block
        items = associations + enum_predicates + @normalizers + methods + model_methods
        items.empty? ? nil : "impl #{@name} {\n#{items.join("\n\n")}\n}"
      end

      def associations
        @model["associations"].filter_map { |assoc| @app.attempt { association(assoc) } }
      end

      def association(assoc)
        return through_constant(assoc) if assoc["options"]["through"]

        extra = assoc["options"].keys - ASSOCIATION_OPTIONS
        unless extra.empty?
          raise Unsupported, "#{@path}: #{assoc["macro"]} :#{assoc["name"]} with #{extra.join(", ")} isn't supported yet"
        end

        target = assoc["class_name"]
        @uses.model(target) unless target == @name
        const = Names.constant(assoc["name"])
        name = Names.str(assoc["name"])
        key = Names.str(assoc["foreign_key"])
        case assoc["macro"]
        when "belongs_to"
          @uses.rt("BelongsTo")
          "// belongs_to :#{assoc["name"]}\npub const #{const}: BelongsTo<#{@name}, #{target}> = BelongsTo::new(#{name}, #{key});"
        when "has_many"
          @uses.rt("HasMany")
          "// has_many :#{assoc["name"]}\npub const #{const}: HasMany<#{@name}, #{target}> = " \
            "HasMany::new(#{name}, #{key}, #{inverse(assoc)});"
        else
          raise Unsupported, "#{@path}: #{assoc["macro"]} :#{assoc["name"]} isn't supported yet"
        end
      end

      def through_constant(assoc)
        link, source = ModelFile.through_parts(@app, @name, assoc)
        unless link
          raise Unsupported, "#{@path}: has_many :#{assoc["name"]} through #{assoc["options"]["through"]} in this shape " \
                             "isn't supported yet"
        end

        @uses.rt("HasManyThrough")
        target = assoc["class_name"]
        @uses.model(target) unless target == @name
        table = @app.model(link["class_name"])["table_name"]
        "// has_many :#{assoc["name"]}, through: :#{link["name"]}\npub const #{Names.constant(assoc["name"])}: " \
          "HasManyThrough<#{@name}, #{target}> = HasManyThrough::new(#{Names.str(assoc["name"])}, #{Names.str(table)}, " \
          "#{Names.str(link["foreign_key"])}, #{Names.str(source["foreign_key"])});"
      end

      # has_many's inverse, as Rails resolved it: the target's belongs_to
      # back to this model, or none (inverse_of: false, or a foreign_key:
      # option without inverse_of:, which stops Rails looking).
      def inverse(assoc)
        name = assoc.fetch("inverse_of") or return "None"
        back = @app.association(assoc["class_name"], name)
        unless back && back["macro"] == "belongs_to" && back["class_name"] == @name
          raise Unsupported, "#{@path}: has_many :#{assoc["name"]} with the inverse :#{name} isn't supported yet"
        end
        "Some(&#{assoc["class_name"]}::#{Names.constant(name)})"
      end

      def enum_predicates
        @model["enums"].flat_map do |attribute, values|
          values.keys.map.with_index do |label, i|
            comment = i.zero? ? "// enum :#{attribute}\n" : ""
            "#{comment}pub fn is_#{label}(&self) -> bool {\nself.#{attribute}.as_deref() == Some(#{Names.str(label)})\n}"
          end
        end
      end

      # The callback methods the Behavior chain names, one fn each.
      def methods
        @hooks.filter_map { |name| @app.attempt { callback_method(name) } }
      end

      # The model's own methods: every public one, and the private ones
      # something in this file calls.
      def model_methods
        registry = @app.model_methods
        @app.attempt([]) { registry.publics(@name) }.each do |name|
          @app.attempt { registry.type(@name, name, [@path, registry.definition(@name, name).first]) }
        end
        registry.translated(@name).map do |entry|
          @uses.merge(entry.uses) or raise Unsupported.at(@path, entry.node, "a constant meaning two things in #{@name}")
          entry.rust
        end
      end

      def callback_method(name)
        node = @app.source.def_node(@path, name)
        raise Unsupported.at(@path, node, "a callback method with parameters") if node.parameters

        lines = translate(node.body)
        ctx, record = parameter_names(lines)
        @uses.rt("Ctx", "Handle", "Result")
        "// #{@path}:#{node.location.start_line}\n" \
          "fn #{Names.method(name)}(#{ctx}: &mut Ctx, #{record}: Handle<#{@name}>) -> Result<()> {\n" \
          "#{lines.join("\n")}\nOk(())\n}"
      end

      def translate(body, block: false)
        Translator.new(@app, @path, @uses, env: :model, model: @name, self_var: var, block:).body(body, :unit).first
      end

      def var = Names.var(@name)

      # `ctx` and the record, underscored when the body leaves them unused.
      def parameter_names(lines)
        text = lines.join("\n")
        [Names.mentions?(text, "ctx") ? "ctx" : "_ctx", Names.mentions?(text, var) ? var : "_#{var}"]
      end
    end
  end
end
