module Rutile
  module Build
    # src/jobs/<job>.rs: an Active Job class. `run` is its perform, with the
    # parameters its signature types; `perform` is what a worker calls, with
    # the arguments Active Job serialized (a record by its GlobalID).
    class JobFile
      attr_reader :name

      def initialize(app, job)
        @app = app
        @job = job
        @name = job["name"]
        @path = job.dig("perform", "path") || job.dig("source", "path")
        @uses = Uses.new
      end

      def file_name = "src/jobs/#{module_name}.rs"
      def module_name = Names.snake(@name)
      def constant = Names.constant(module_name)
      def queue = @job["queue"]

      def to_rust
        raise Unsupported, "#{@path}: the namespaced job #{@name} isn't supported yet" if @name.include?("::")

        # retry_on, discard_on, sidekiq_options and callbacks in ApplicationJob
        # apply here too, and the job's own when its perform is inherited.
        [@path, @job.dig("source", "path"), *@job["ancestors"]].compact.uniq.each { Declarations.check(@app, _1, %w[queue_as]) }
        if @job["queue_prefix"]
          raise Unsupported, "#{@path}: queue_name_prefix (#{@job["queue_prefix"]}), which Rails usually sets per environment, " \
                             "isn't supported yet"
        end
        raise Unsupported, "#{@path}: #{@name} without a perform isn't supported yet" unless @job["perform"]
        raise Unsupported, "#{@path}: #{@name}'s queue, which a block decides, isn't supported yet" unless @job["queue"]
        raise Unsupported, "#{@path}: #{@name} with enqueue_after_transaction_commit isn't supported yet" if @job["after_commit"]

        node = @app.source.def_node(@path, "perform")
        signature = Signatures.of(@app, @path, node)
        params = signature&.params || []
        raise Unsupported.at(@path, node, "a perform with parameters and no rbs-inline signature") if node.parameters && !signature
        unless params.all? { _1.kind == :req }
          raise Unsupported.at(@path, node, "a perform with optional or keyword parameters")
        end

        translator = Translator.new(@app, @path, @uses, env: :job)
        declared = params.map do |param|
          rust = Names.parameter(param.name, %w[ctx arguments])
          translator.declare(param.name, rust, param.type)
          @uses.type(param.type)
          [rust, param]
        end
        lines, = translator.body(node.body, :unit)
        @uses.rt("Ctx", "Json", "Result")
        @uses.line("use rustonrails::jobs::{self, Job};")
        header = "//! Generated by Rutile from #{@path}. Edit the Ruby, not this file."
        [header, @uses.lines("crate::models"), definition, run(node, lines, declared), perform(declared)].join("\n\n") + "\n"
      end

      private

      def definition
        "// #{@job.dig("source", "path")}:#{@job.dig("source", "line")}\n" \
          "pub const #{constant}: Job = Job { class: #{Names.str(@name)}, queue: #{Names.str(@job["queue"])} };"
      end

      def run(node, lines, declared)
        text = [*lines, *Names.ended(lines)].join("\n")
        used = ->(name) { Names.mentions?(text, name) ? name : "_#{name}" }
        arguments = ["#{used.("ctx")}: &mut Ctx", *declared.map { |rust, param| "#{used.(rust)}: #{param.type.rust}" }]
        "// #{@path}:#{node.location.start_line}\npub fn run(#{arguments.join(", ")}) -> Result<()> {\n#{text}\n}"
      end

      # Active Job's arguments, in the perform's order and types.
      def perform(declared)
        lines = declared.each_with_index.map do |(rust, param), index|
          value = if param.type.kind == :record
                    "jobs::record_at::<#{param.type.model}>(ctx, arguments, #{index})?"
                  elsif scalar?(param.type)
                    "jobs::scalar_at::<#{param.type.rust}>(arguments, #{index})?"
                  else
                    raise Unsupported, "#{@path}: #{@name}'s #{param.name}, #{param.type.kind}, as a job argument isn't supported yet"
                  end
          "let #{rust} = #{value};"
        end
        call = "run(#{["ctx", *declared.map(&:first)].join(", ")})"
        # Ruby checks the count before perform runs.
        lines.unshift("jobs::arity(arguments, #{declared.size})?;")
        "/// What a worker runs, with the arguments Active Job serialized.\n" \
          "pub fn perform(ctx: &mut Ctx, arguments: &[Json]) -> Result<()> {\n" \
          "#{[*lines, call].join("\n")}\n}"
      end

      def scalar?(type) = [T::INT, T::FLOAT, T::STR, T::BOOL].include?(type.nilable? ? type.inner : type)
    end
  end
end
