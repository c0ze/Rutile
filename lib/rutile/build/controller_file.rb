module Rutile
  module Build
    # src/controllers/<name>.rs: a struct whose fields are the controller's
    # instance variables; wrap_parameters, before_action and rescue_from as
    # the `Controller` trait; then the actions and the helpers they call.
    class ControllerFile
      include Rescues

      APPLICATION = "app/controllers/application_controller.rb"
      # What a helper may return: the types with a Rust spelling.
      RETURNABLE = %i[record relation nilable str int float bool time date value json attributes].freeze

      # Every app controller that has actions.
      def self.all(app) = app.controllers.reject { _1["actions"].empty? }.map { new(app, _1["name"]) }

      attr_reader :name

      def initialize(app, name)
        @app = app
        @name = name
        @controller = app.controller(name)
        @path = @controller.dig("source", "path")
        @uses = Uses.new
        @ivars = {}
        @helpers = {}
      end

      def file_name = "#{Names.snake(@name.delete_suffix("Controller"))}.rs"

      def to_rust
        raise Unsupported, "#{@path}: the namespaced controller #{@name} isn't supported yet" if @name.include?("::")

        Declarations.check(@app, @path, Declarations::CONTROLLER)
        @uses.rt("Controller", "Request", "Response", "Result")
        filters = filter_lines
        actions = defs.select { @controller["actions"].include?(_1.name.to_s) }.filter_map { |node| @app.attempt { action(node) } }
        trait = controller_impl(filters)
        header = "//! Generated by Rutile from #{@path}. Edit the Ruby, not this file."
        methods = actions + @helpers.values.filter_map { _1&.fetch(:rust, nil) }
        body = [struct, trait, "impl #{@name} {\n#{methods.join("\n\n")}\n}"]
        [header, @uses.lines("crate::models"), *body].join("\n\n") + "\n"
      end

      def ivar(name, type, node)
        field = type.nilable? ? type.inner : type
        raise Unsupported.at(@path, node, "@#{name} holding different types") if @ivars[name] && @ivars[name] != field

        @ivars[name] = field
      end

      # Unknown after a filter failed: the filter is already reported, and
      # whatever reads what it would have set is skipped.
      # Ruby's lookup order: this class's methods and readers, then
      # ApplicationController's.
      def reader?(name)
        [@path, APPLICATION].each do |path|
          return false if @app.source.defs(path).any? { _1.name.to_s == name }
          return true if readers(path).include?(name)
        end
        false
      end

      def readers(path)
        Declarations.calls(@app.source.tree(path), "attr_reader").flat_map { |call| call.arguments.arguments.map(&:unescaped) }
      end

      def ivar_type(name) = @ivars[name] || (@filter_failed ? raise(Skipped, name) : nil)

      # A method of this controller that isn't an action, translated the
      # first time something calls it. A filter returns nothing; a helper
      # returns its last value; a rescue handler returns a response, and
      # may take the exception.
      def helper(name, _node, tail: :value)
        if @helpers.key?(name)
          raise Skipped, name if @helpers[name]&.fetch(:failed, false)

          return @helpers[name]&.fetch(:type)
        end
        return nil if @controller["actions"].include?(name)

        found = definition(name) or return nil
        node, path = found
        @helpers[name] = nil
        @helpers[name] = @app.attempt({ failed: true }) { translate_helper(name, node, path, tail) }
        if @helpers[name][:failed]
          @filter_failed = true if %i[unit filter].include?(tail)
          raise Skipped, name
        end

        @helpers[name][:type]
      end

      # A helper's rbs-inline signature, once `helper` has translated it.
      def signature(name) = @helpers[name]&.fetch(:signature, nil)

      private

      def translate_helper(name, node, path, tail)
        parameter = Rescues.parameter(@app, path, node) if tail == :response
        signature = Signatures.of(@app, path, node) unless parameter
        if node.parameters && !parameter
          raise Unsupported.at(path, node, "a controller method with parameters and no rbs-inline signature") unless signature
          # Rails calls a filter with no arguments.
          raise Unsupported.at(path, node, "a before_action method with parameters") if %i[unit filter].include?(tail)
        end
        declared = signature&.returns
        tail = :unit if declared == T::UNIT && tail == :value
        translator = translator(path, returns: tail == :value ? declared : nil)
        exception = parameter && Rescues.declare(translator, @uses, node, parameter)
        params = (signature&.params || []).map do |param|
          rust = Names.parameter(param.name, %w[req ctx self])
          translator.declare(param.name, rust, param.type)
          @uses.type(param.type)
          [rust, param.type]
        end
        lines, type = translator.body(node.body, tail)
        type = declared if declared && tail == :value
        returned = { unit: "()", response: "Response", filter: "Option<Response>" }.fetch(tail) do
          raise Unsupported.at(path, node, "a helper returning #{type.kind}") unless RETURNABLE.include?(type.kind)

          @uses.type(type)
          type.rust
        end
        lines.concat(Names.ended(lines)) if tail == :unit
        arguments = params.map { |rust, param_type| "#{Names.mentions?(lines, rust) ? rust : "_#{rust}"}: #{param_type.rust}" }
        rust = "// #{path}:#{node.location.start_line}\n" \
               "fn #{Names.method(name)}(#{["&mut self", "#{req(lines)}: &mut Request", *exception, *arguments].join(", ")}) " \
               "-> Result<#{returned}> {\n#{lines.join("\n")}\n}"
        { type: %i[unit filter].include?(tail) ? T::UNIT : type, rust:, signature: }
      end

      def defs = @app.source.defs(@path)

      def translator(path = @path, returns: nil) = Translator.new(@app, path, @uses, env: :controller, controller: self, returns:)

      # Private methods come from this file, then ApplicationController:
      # Rust has no inheritance, so an inherited method is translated into
      # every controller that uses it.
      def definition(name)
        [@path, APPLICATION].each do |path|
          node = @app.source.defs(path).find { _1.name.to_s == name }
          return [node, path] if node
        end
        nil
      end

      def req(lines) = Names.mentions?(lines, "req") ? "req" : "_req"

      def action(node)
        raise Unsupported.at(@path, node, "an action with parameters") if node.parameters

        lines, = translator.body(node.body, :response)
        "// #{@path}:#{node.location.start_line}\n" \
          "pub fn #{node.name}(&mut self, #{req(lines)}: &mut Request) -> Result<Response> {\n#{lines.join("\n")}\n}"
      end

      def struct
        fields = @ivars.map do |name, type|
          @uses.type(type)
          "#{name}: Option<#{type.rust}>,"
        end
        body = fields.empty? ? ";" : " {\n#{fields.join("\n")}\n}"
        "// #{@path}:#{@controller.dig("source", "line")}\n#[derive(Default)]\npub struct #{@name}#{body}"
      end

      # before_action calls, guarded by the action lists Rails keeps as
      # `if:`/`unless:` conditions.
      def filter_lines
        @controller["filters"].flat_map { |filter| @app.attempt([]) { filter_line(filter) } }
      end

      def filter_line(filter)
        method = filter.dig("filter", "method")
        path = filter.dig("filter", "source", "path")
        unsupported!("#{filter["kind"]}_action") unless filter["kind"] == "before"
        unsupported!("a before_action that isn't a method") unless method
        unsupported!("before_action :#{method} from #{path || "outside the app"}") unless [@path, APPLICATION].include?(path)

        halts = renders?(definition(method)&.first)
        helper(method, nil, tail: halts ? :filter : :unit)
        guards = filter["if"].map { guard(_1, "") } + filter["unless"].map { guard(_1, "!") }
        comment = "// before_action :#{method}#{" (#{path})" unless path == @path}"
        call = if halts
                 ["if let Some(response) = self.#{Names.method(method)}(req)? {", "return Ok(Some(response));", "}"]
               else
                 ["self.#{Names.method(method)}(req)?;"]
               end
        guards.empty? ? [comment, *call] : [comment, "if #{guards.join(" && ")} {", *call, "}"]
      end

      # Whether a method body renders or heads: then it's a filter that can halt.
      def renders?(node)
        return false unless node

        node.is_a?(Prism::CallNode) && node.receiver.nil? && %i[render head].include?(node.name) ||
          node.compact_child_nodes.any? { renders?(_1) }
      end

      # One `if:`/`unless:` entry: an action list. Rails requires them all.
      def guard(condition, negate)
        unsupported!("before_action conditions other than only: and except:") unless condition.key?("actions")

        actions = condition["actions"]
        return negate.empty? ? "false" : "true" if actions.empty?

        "#{negate}matches!(action, #{actions.map { Names.str(_1) }.join(" | ")})"
      end

      def controller_impl(filters)
        items = [@app.attempt { wrap_parameters }]
        unless filters.empty?
          action = filters.any? { _1.include?("matches!(action") } ? "action" : "_action"
          items << "fn before(&mut self, req: &mut Request, #{action}: &str) -> Result<Option<Response>> {\n" \
                   "#{filters.join("\n")}\nOk(None)\n}"
        end
        unless @controller["rescue_handlers"].empty?
          @uses.rt("Error")
          arms = rescue_arms
          request = arms.any? { _1.match?(/\(req\b/) } ? "req" : "_req"
          items << "fn rescue(&mut self, #{request}: &mut Request, error: Error) -> Result<Response> {\n" \
                   "match error {\n#{arms.join("\n")}\nother => Err(other),\n}\n}"
        end
        "impl Controller for #{@name} {\n#{items.compact.join("\n\n")}\n}"
      end

      def wrap_parameters
        wrap = @controller["param_wrapping"] or return nil
        unless wrap["format"] == ["json"] && wrap["include"] && wrap["exclude"].nil?
          unsupported!("wrap_parameters other than the default for a model")
        end

        "fn wrap_parameters() -> Option<(&'static str, &'static [&'static str])> {\n" \
          "Some((#{Names.str(wrap["name"])}, #{Names.str_slice(wrap["include"])}))\n}"
      end

      def unsupported!(what) = raise(Unsupported, "#{@path}: #{what} isn't supported yet")
    end
  end
end
