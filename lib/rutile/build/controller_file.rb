module Rutile
  module Build
    # src/controllers/<name>.rs: a struct whose fields are the controller's
    # instance variables; wrap_parameters, before_action and rescue_from as
    # the `Controller` trait; then the actions and the helpers they call.
    class ControllerFile
      EXCEPTIONS = {
        "ActiveRecord::RecordNotFound" => "RecordNotFound", "ActiveRecord::RecordInvalid" => "RecordInvalid",
        "ActiveRecord::RecordNotSaved" => "RecordNotSaved", "ActiveRecord::RecordNotDestroyed" => "RecordNotDestroyed",
        "ActionController::ParameterMissing" => "ParameterMissing"
      }.freeze
      APPLICATION = "app/controllers/application_controller.rb"

      # Every app controller that has actions.
      def self.all(app) = app.controllers.reject { _1["actions"].empty? }.map { new(app, _1["name"]) }

      attr_reader :name

      def initialize(app, name)
        @app = app
        @name = name
        @controller = app.controller(name)
        @path = @controller.dig("source", "path")
        @uses = Uses.new
        @ivars = {}
        @helpers = {}
      end

      def file_name = "#{Names.snake(@name.delete_suffix("Controller"))}.rs"

      def to_rust
        raise Unsupported, "#{@path}: the namespaced controller #{@name} isn't supported yet" if @name.include?("::")

        Declarations.check(@app, @path, Declarations::CONTROLLER)
        @uses.rt("Controller", "Request", "Response", "Result")
        filters = filter_lines
        actions = defs.select { @controller["actions"].include?(_1.name.to_s) }.filter_map { |node| @app.attempt { action(node) } }
        trait = controller_impl(filters)
        header = "//! Generated by Rutile from #{@path}. Edit the Ruby, not this file."
        methods = actions + @helpers.values.filter_map { _1&.fetch(:rust, nil) }
        body = [struct, trait, "impl #{@name} {\n#{methods.join("\n\n")}\n}"]
        [header, @uses.lines("crate::models"), *body].join("\n\n") + "\n"
      end

      def ivar(name, type, node)
        field = type.nilable? ? type.inner : type
        raise Unsupported.at(@path, node, "@#{name} holding different types") if @ivars[name] && @ivars[name] != field

        @ivars[name] = field
      end

      def ivar_type(name) = @ivars[name]

      # A method of this controller that isn't an action, translated the
      # first time something calls it. A filter returns nothing; a helper
      # returns its last value; a rescue handler returns a response.
      def helper(name, _node, tail: :value)
        if @helpers.key?(name)
          raise Skipped, name if @helpers[name]&.fetch(:failed, false)

          return @helpers[name]&.fetch(:type)
        end
        return nil if @controller["actions"].include?(name)

        node = defs.find { _1.name.to_s == name } or return nil
        @helpers[name] = nil
        @helpers[name] = @app.attempt({ failed: true }) { translate_helper(name, node, tail) }
        raise Skipped, name if @helpers[name][:failed]

        @helpers[name][:type]
      end

      private

      def translate_helper(name, node, tail)
        raise Unsupported.at(@path, node, "a controller method with parameters") if node.parameters

        lines, type = translator.body(node.body, tail)
        returned = { unit: "()", response: "Response" }.fetch(tail) do
          @uses.type(type)
          type.rust
        end
        lines << "Ok(())" if tail == :unit
        rust = "// #{@path}:#{node.location.start_line}\n" \
               "fn #{Names.method(name)}(&mut self, #{req(lines)}: &mut Request) -> Result<#{returned}> {\n#{lines.join("\n")}\n}"
        { type: tail == :unit ? T::UNIT : type, rust: }
      end

      def defs = @app.source.defs(@path)

      def translator = Translator.new(@app, @path, @uses, env: :controller, controller: self)

      def req(lines) = lines.join("\n").match?(/\breq\b/) ? "req" : "_req"

      def action(node)
        raise Unsupported.at(@path, node, "an action with parameters") if node.parameters

        lines, = translator.body(node.body, :response)
        "// #{@path}:#{node.location.start_line}\n" \
          "pub fn #{node.name}(&mut self, #{req(lines)}: &mut Request) -> Result<Response> {\n#{lines.join("\n")}\n}"
      end

      def struct
        fields = @ivars.map do |name, type|
          @uses.type(type)
          "#{name}: Option<#{type.rust}>,"
        end
        body = fields.empty? ? ";" : " {\n#{fields.join("\n")}\n}"
        "// #{@path}:#{@controller.dig("source", "line")}\n#[derive(Default)]\npub struct #{@name}#{body}"
      end

      # before_action calls, guarded by the action lists Rails keeps as
      # `if:`/`unless:` conditions.
      def filter_lines
        @controller["filters"].flat_map { |filter| @app.attempt([]) { filter_line(filter) } }
      end

      def filter_line(filter)
        method = filter.dig("filter", "method")
        unsupported!("#{filter["kind"]}_action") unless filter["kind"] == "before"
        unsupported!("a before_action that isn't a method of #{@name}") unless method && filter.dig("filter", "source", "path") == @path

        helper(method, nil, tail: :unit)
        guards = filter["if"].map { guard(_1, "") } + filter["unless"].map { guard(_1, "!") }
        comment = "// before_action :#{method}"
        call = "self.#{Names.method(method)}(req)?;"
        guards.empty? ? [comment, call] : [comment, "if #{guards.join(" && ")} {", call, "}"]
      end

      # One `if:`/`unless:` entry: an action list. Rails requires them all.
      def guard(condition, negate)
        unsupported!("before_action conditions other than only: and except:") unless condition.key?("actions")

        "#{negate}matches!(action, #{condition["actions"].map { Names.str(_1) }.join(" | ")})"
      end

      def controller_impl(filters)
        items = [@app.attempt { wrap_parameters }]
        unless filters.empty?
          action = filters.any? { _1.include?("matches!(action") } ? "action" : "_action"
          items << "fn before(&mut self, req: &mut Request, #{action}: &str) -> Result<Option<Response>> {\n" \
                   "#{filters.join("\n")}\nOk(None)\n}"
        end
        unless @controller["rescue_handlers"].empty?
          @uses.rt("Error")
          arms = rescue_arms
          request = arms.any? { _1.include?("(req)") } ? "req" : "_req"
          items << "fn rescue(&mut self, #{request}: &mut Request, error: Error) -> Result<Response> {\n" \
                   "match error {\n#{arms.join("\n")}\nother => Err(other),\n}\n}"
        end
        "impl Controller for #{@name} {\n#{items.compact.join("\n\n")}\n}"
      end

      def wrap_parameters
        wrap = @controller["param_wrapping"] or return nil
        unless wrap["format"] == ["json"] && wrap["include"] && wrap["exclude"].nil?
          unsupported!("wrap_parameters other than the default for a model")
        end

        "fn wrap_parameters() -> Option<(&'static str, &'static [&'static str])> {\n" \
          "Some((#{Names.str(wrap["name"])}, #{Names.str_slice(wrap["include"])}))\n}"
      end

      # Rails tries the handler registered last first; a class already
      # matched shadows later arms for it.
      def rescue_arms
        seen = Set.new
        @controller["rescue_handlers"].reverse.filter_map do |handler|
          @app.attempt do
            variant = EXCEPTIONS[handler["exception"]] or unsupported!("rescue_from #{handler["exception"]}")
            next unless seen.add?(variant)

            method = handler.dig("handler", "method") or unsupported!("a rescue_from block")
            "// rescue_from #{handler["exception"]}, with: :#{method}\nError::#{variant} { .. } => #{handler_call(handler, method)},"
          end
        end
      end

      def handler_call(handler, method)
        case handler.dig("handler", "source", "path")
        when @path
          helper(method, nil, tail: :response)
          "self.#{Names.method(method)}(req)"
        when APPLICATION
          @uses.line("use super::application;")
          "application::#{Names.method(method)}(req)"
        else unsupported!("rescue_from handled outside #{@name} and ApplicationController")
        end
      end

      def unsupported!(what) = raise(Unsupported, "#{@path}: #{what} isn't supported yet")
    end

    # src/controllers/application.rs: the ApplicationController methods
    # other controllers' rescue_from handlers call, as plain functions.
    class ApplicationControllerFile
      PATH = ControllerFile::APPLICATION

      def initialize(app)
        @app = app
        @uses = Uses.new
      end

      def to_rust
        Declarations.check(@app, PATH, Declarations::CONTROLLER)
        functions = handlers.filter_map { |name| @app.attempt { function(name) } }
        header = "//! Generated by Rutile from #{PATH}. Edit the Ruby, not this file."
        [header, @uses.lines("crate::models"), *functions].reject(&:empty?).join("\n\n") + "\n"
      end

      # These run without a controller instance.
      def ivar(name, _type, node) = raise(Unsupported.at(PATH, node, "@#{name} in ApplicationController"))
      def ivar_type(_name) = nil
      def helper(_name, _node) = nil

      private

      def handlers
        @app.controllers.flat_map { _1["rescue_handlers"] }
                        .select { _1.dig("handler", "source", "path") == PATH }
                        .map { _1.dig("handler", "method") }.uniq
      end

      def function(name)
        node = @app.source.def_node(PATH, name)
        raise Unsupported.at(PATH, node, "a rescue handler with parameters") if node.parameters

        @uses.rt("Request", "Response", "Result")
        lines, = Translator.new(@app, PATH, @uses, env: :controller, controller: self).body(node.body, :response)
        req = lines.join("\n").match?(/\breq\b/) ? "req" : "_req"
        "// #{PATH}:#{node.location.start_line}\npub fn #{Names.method(name)}(#{req}: &mut Request) -> Result<Response> {\n" \
          "#{lines.join("\n")}\n}"
      end
    end
  end
end
