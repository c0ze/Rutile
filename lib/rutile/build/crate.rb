require "fileutils"
require "open3"
require "pathname"

module Rutile
  module Build
    # Writes the crate: Cargo.toml only when it's missing, all of src/ from
    # scratch, then rustfmt, then `cargo check` as the gate. Everything is
    # generated before anything is written, so an unsupported construct
    # leaves the previous crate as it was.
    class Crate
      def initialize(app, out, name:, runtime:)
        @app = app
        @out = out
        @name = name
        @runtime = runtime
      end

      def files
        models = @app.models.map { ModelFile.new(@app, _1["name"]) }
        record = ApplicationRecordFile.new(@app)
        controllers = ControllerFile.all(@app)
        files = models.to_h { ["src/models/#{_1.file_name}", _1.to_rust] }
        files["src/models/application_record.rs"] = record.to_rust unless record.empty?
        files["src/models/mod.rs"] = models_mod(models, record)
        controllers.each { files["src/controllers/#{_1.file_name}"] = _1.to_rust }
        files["src/controllers/application.rs"] = ApplicationControllerFile.new(@app).to_rust
        files["src/controllers/mod.rs"] = controllers_mod(controllers)
        files["src/routes.rs"] = RoutesFile.new(@app).to_rust
        files.merge("src/lib.rs" => lib_rs, "src/main.rs" => main_rs)
      end

      def write
        generated = files
        FileUtils.mkdir_p(@out)
        cargo = File.join(@out, "Cargo.toml")
        File.write(cargo, cargo_toml) unless File.exist?(cargo)
        FileUtils.rm_rf(File.join(@out, "src"))
        paths = generated.map do |path, text|
          full = File.join(@out, path)
          FileUtils.mkdir_p(File.dirname(full))
          File.write(full, text)
          full
        end
        run!("rustfmt", "--edition", "2024", *paths)
        run!("cargo", "check", "--quiet", "--manifest-path", cargo)
      end

      private

      # A failure or a warning here is a Rutile bug, not the app's.
      def run!(*command)
        output, status = Open3.capture2e(*command)
        return if status.success? && !output.match?(/^warning/)

        raise Error, "#{command.first} #{command[1]} failed on the generated crate in #{@out}:\n#{output}"
      end

      def cargo_toml
        runtime = Pathname(@runtime).relative_path_from(Pathname(File.expand_path(@out)))
        <<~TOML
          [package]
          name = "#{@name}"
          version = "0.1.0"
          edition = "2024"
          publish = false

          [dependencies]
          rustonrails = { path = "#{runtime}" }
        TOML
      end

      def models_mod(models, record)
        modules = models.map { File.basename(_1.file_name, ".rs") }
        exports = models.map { [File.basename(_1.file_name, ".rs"), _1.exports] }
        unless record.empty?
          modules.unshift("application_record")
          exports.unshift(["application_record", ["ApplicationRecordScopes"]])
        end
        uses = exports.map { |mod, names| "pub use #{mod}::#{names.size == 1 ? names.first : "{#{names.join(", ")}}"};" }
        "//! Generated by Rutile from app/models. Edit the Ruby, not this file.\n\n" \
          "#{modules.map { "mod #{_1};" }.join("\n")}\n\n#{uses.join("\n")}\n"
      end

      def controllers_mod(controllers)
        modules = controllers.map { File.basename(_1.file_name, ".rs") }
        "//! Generated by Rutile from app/controllers. Edit the Ruby, not this file.\n\npub mod application;\n" \
          "#{modules.map { "mod #{_1};" }.join("\n")}\n\n" \
          "#{controllers.zip(modules).map { |c, mod| "pub use #{mod}::#{c.name};" }.join("\n")}\n"
      end

      def lib_rs
        "//! Generated by Rutile from #{File.basename(@app.root)}. Edit the Ruby, not this crate's src/.\n\n" \
          "pub mod controllers;\npub mod models;\npub mod routes;\n"
      end

      def main_rs
        <<~RUST
          //! Generated by Rutile. Serves the app: `DATABASE_URL`, `BIND` (default
          //! 127.0.0.1:3000) and `WORKERS` (default 5, like Puma's threads).

          use rustonrails::server::{self, Config};

          fn main() -> Result<(), Box<dyn std::error::Error + Send + Sync>> {
              let config = Config {
                  address: std::env::var("BIND").unwrap_or_else(|_| "127.0.0.1:3000".into()),
                  database_url: std::env::var("DATABASE_URL").map_err(|_| "DATABASE_URL is not set")?,
                  workers: std::env::var("WORKERS").ok().and_then(|w| w.parse().ok()).unwrap_or(5),
              };
              let running = server::start(#{@name}::routes::routes(), config)?;
              eprintln!("#{@name} listening on {}", running.address);
              running.join();
              Ok(())
          }
        RUST
      end
    end
  end
end
