module Rutile
  module Build
    # src/routes.rs: config/routes.rb in the order Rails matches it, with
    # each constraint lambda as a function.
    class RoutesFile
      PATH = "config/routes.rb"
      VERBS = %w[GET POST PATCH PUT DELETE].freeze

      def initialize(app)
        @app = app
        @uses = Uses.new
        @controllers = Set.new
        @constraints = []
      end

      # What Rails' middleware does around every route: the cookie store,
      # cookies' SameSite, force_ssl, the default headers, the public pages.
      def middleware
        config = @app.manifest["config"]
        same_site = same_site(config["cookies_same_site"], "cookies_same_site_protection")
        lines = [session_store(config["session"], same_site), (".cookies_same_site(#{same_site})" unless same_site == 'Some("lax")'),
                 force_ssl(config), default_headers(config["default_headers"]), *public_pages]
        lines.compact.map { "\n#{_1}" }.join
      end

      def session_store(session, same_site)
        return nil unless session && session["store"] == "cookie"

        unsupported!("the session cookie's domain: option") if session["domain"]
        unsupported!("the session cookie's expire_after: option") if session["expire_after"]
        own = session["same_site"] == "default" ? same_site : same_site(session["same_site"], "the session cookie's same_site:")
        return ".session_store(#{Names.str(session["key"])})" if session.slice("path", "secure", "httponly") ==
                                                                   { "path" => "/", "secure" => false, "httponly" => true } && own == 'Some("lax")'

        @uses.rt("CookieOptions")
        ".session_store_with(#{Names.str(session["key"])}, CookieOptions { path: #{Names.str(session["path"])}, " \
          "secure: #{session["secure"]}, httponly: #{session["httponly"]}, same_site: #{own}.map(str::to_string) })"
      end

      def same_site(value, what)
        return "None" if value.nil?
        unsupported!("#{what} decided per request") unless value.is_a?(String)
        unsupported!("#{what} #{value}") unless %w[lax strict none].include?(value)

        "Some(#{Names.str(value)})"
      end

      # Behind `assume_ssl` every request is HTTPS, so force_ssl is HSTS and
      # secure cookies; without it, force_ssl redirects, which isn't done here.
      def force_ssl(config)
        return nil unless config["force_ssl"]

        unsupported!("force_ssl without assume_ssl (redirecting plain HTTP)") unless config["assume_ssl"]
        unless [{}, { "hsts" => { "subdomains" => true } }].include?(config["ssl_options"] || {})
          unsupported!("ssl_options other than Rails' defaults")
        end
        ".force_ssl()"
      end

      def default_headers(headers)
        return nil if headers.nil? || headers.empty?

        ".default_headers(&[#{headers.map { |name, value| "(#{Names.str(name)}, #{Names.str(value.to_s)})" }.join(", ")}])"
      end

      # public/404.html and the rest, which Rails' exceptions app sends an
      # HTML request (a page for the default locale first).
      def public_pages
        locale = @app.manifest.dig("config", "default_locale")
        Dir.glob("public/[0-9][0-9][0-9]{.#{locale},}.html", base: @app.root).map { File.basename(_1)[0, 3].to_i }.uniq.sort.map do |status|
          file = ["public/#{status}.#{locale}.html", "public/#{status}.html"].find { File.file?(File.join(@app.root, _1)) }
          ".public_page(#{status}, #{Names.str(File.read(File.join(@app.root, file), encoding: Encoding::UTF_8))})"
        end
      end

      def to_rust
        @uses.rt("Router")
        routes = @app.routes.flat_map { |route| @app.attempt([]) { route(route) } }
        @uses.line("use crate::controllers::{#{@controllers.sort.join(", ")}};") unless @controllers.empty?
        body = "/// #{PATH}, in the order Rails matches it.\npub fn routes() -> Router {\nRouter::new()#{middleware}\n#{routes.join("\n")}\n}"
        header = "//! Generated by Rutile from #{PATH}. Edit the Ruby, not this file."
        paths = Paths.functions(@app)
        @uses.rt("Result") unless paths.empty?
        @uses.rt("ToParam", "path_segment") if paths.any? { _1.include?("impl ToParam") }
        [header, @uses.lines("crate::models"), body, *@constraints, *paths].join("\n\n") + "\n"
      end

      private

      def route(route)
        where = "#{route["verb"]} #{route["path"]}#{" #{route["controller"]}##{route["action"]}" if route["controller"]}"
        unsupported!("#{where}: a route without a controller (a redirect or a mount)") unless route["controller"]
        unsupported!("#{where}: requirements") unless route["requirements"].empty?
        unsupported!("#{where}: request constraints") unless route["request_constraints"].empty?
        handler = handler(route, where)
        route["verb"].split("|").flat_map do |verb|
          unsupported!("#{where}: #{verb}") unless VERBS.include?(verb)
          constraints = route["callable_constraints"].map { constraint(_1, route, where) }
          ["// #{where}", ".#{verb.downcase}(#{Names.str(route["path"])}, #{handler})", *constraints]
        end
      end

      def handler(route, where)
        if route["controller"] == "rails/health" && route["action"] == "show"
          @uses.rt("health")
          return "Box::new(health)"
        end
        unsupported!("#{where}: a namespaced controller") if route["controller"].include?("/")

        name = "#{Names.camel(route["controller"])}Controller"
        controller = @app.controllers.find { _1["name"] == name } or unsupported!("#{where}: #{name}, which the app doesn't define")
        unsupported!("#{where}: an action #{name} doesn't have") unless controller["actions"].include?(route["action"])

        @uses.rt("action")
        @controllers << name
        "action(#{Names.str(route["action"])}, #{name}::#{route["action"]})"
      end

      # `constraints: ->(request) { ... }` as `fn(&Request) -> bool`.
      def constraint(constraint, route, where)
        location = constraint["proc"] or unsupported!("#{where}: a constraint object")
        node = @app.source.block_at(location["path"], location["line"])
        params = node.parameters.is_a?(Prism::BlockParametersNode) ? node.parameters.parameters&.requireds || [] : []
        unless params.size == 1 && params.first.is_a?(Prism::RequiredParameterNode)
          unsupported!("#{where}: a constraint lambda without one request parameter")
        end

        name = "#{route["controller"]}_#{route["action"]}_constraint"
        name += "_#{@constraints.size + 1}" if @constraints.any? { _1.include?("fn #{name}(") }
        translator = Translator.new(@app, location["path"], @uses, env: :constraint, result: false)
        translator.declare(params.first.name.to_s, "req", T::REQUEST)
        lines, type = translator.body(node.body, :value)
        unsupported!("#{where}: a constraint that isn't true or false") unless type == T::BOOL

        @uses.rt("Request")
        @constraints << "// #{location["path"]}:#{location["line"]}\nfn #{name}(req: &Request) -> bool {\n#{lines.join("\n")}\n}"
        ".constraint(#{name})"
      end

      def unsupported!(what) = raise(Unsupported, "#{PATH}: #{what} isn't supported yet")
    end
  end
end
